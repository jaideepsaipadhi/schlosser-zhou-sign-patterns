import sys
from probe import *
N=int(sys.argv[1]); prec=int(sys.argv[2])
cases=[
 ('G7 d=2.0','G7',2,'+--+++-'),('G7 d=2.5','G7',2.5,'+--+++-'),('G7 d=2.99','G7',2.99,'+--+++-'),
 ('G7 d=3.01','G7',3.01,'+-++---'),('G7 d=4','G7',4,'+-++---'),('G7 d=4.5','G7',4.5,'+-++---'),('G7 d=5','G7',5,'+-++---'),
 ('G11 d=1.76','G11',1.76,'+--+++-+--+'),('G11 d=1.9','G11',1.9,'+--+++-+--+'),('G11 d=2','G11',2,'+--+++-+--+'),
 ('Q12 d=2','Q12',2,'+-+--+-+-++-'),('Q12 d=2.5','Q12',2.5,'+-+--+-+-++-'),('Q12 d=3','Q12',3,'+-+--+-+-++-'),
 ('Q12 d=-0.25','Q12',-0.25,'+++++------+'),('Q12 d=-0.5','Q12',-0.5,'+++++------+'),('Q12 d=-0.75','Q12',-0.75,'+++++------+'),('Q12 d=-0.99','Q12',-0.99,'+++++------+'),
]
E={'G7':G(7),'G11':G(11),'Q12':Q12}
for name,P,d,pat in cases:
    f=coeffs(E[P],N,str(d),prec); sg=signs(f)
    bad,zeros,und=check(sg,pat)
    print('%-12s pattern %-13s violations %4d first %s zeros %s undecided %d'%(name,pat,len(bad),bad[:6],zeros[:6],len(und)),flush=True)
